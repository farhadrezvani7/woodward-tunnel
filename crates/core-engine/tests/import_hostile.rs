fn up() -> Upstream {
    Upstream {
        addr: "127.0.0.1:10808".parse().unwrap(),
        username: "u".into(),
        password: "p".into(),
    }
}

/// Fails when the config carries anything the hostile input tried to bring in.
fn assert_clean(cfg: &Value, what: &str) {
    let text = cfg.to_string();
    for bad in [
        "0.0.0.0\"",
        "\"::\"",
        "7890",
        "1081",
        "9090",
        "evil",
        "6.6.6.6",
        "eth0",
        "clash_api",
        "experimental",
        "StatsService",
        "HandlerService",
        "noauth",
    ] {
        assert!(
            !text.contains(bad),
            "{what}: `{bad}` reached the config: {text}"
        );
    }
    let obj = cfg.as_object().unwrap();
    for k in obj.keys() {
        assert!(
            ["log", "inbounds", "outbounds", "dns", "route", "endpoints"].contains(&k.as_str()),
            "{what}: unexpected top-level key {k}"
        );
    }
    // Exactly one inbound, on loopback or the TUN device we generate ourselves.
    let inb = cfg["inbounds"].as_array().unwrap();
    assert_eq!(inb.len(), 1, "{what}");
    if let Some(l) = inb[0].get("listen") {
        assert_eq!(l, "127.0.0.1", "{what}");
    }
}

#[test]
fn hostile_singbox_json_brings_in_only_the_outbound_server() {
    let a = analyze(SINGBOX_HOSTILE);
    assert_eq!(a.profiles.len(), 1, "{:?}", a.issues);
    let p = &a.profiles[0];
    assert_eq!(p.host, "s.example.com");
    for mode in [Mode::Tun, Mode::Proxy { socks_port: 10808 }] {
        let b = singbox::build(p, &mode, &[]).unwrap();
        assert_clean(&b.config, "sing-box json");
        // Routing is the generated one: everything goes to the proxy outbound, and the only extra
        // rules are the DNS hijack and the QUIC reject of TUN mode.
        assert_eq!(b.config["route"]["final"], "proxy");
        for r in b.config["route"]["rules"].as_array().unwrap_or(&vec![]) {
            assert!(
                r.get("outbound").is_none() && r.get("ip_cidr").is_none(),
                "route rule {r} was not generated by us"
            );
        }
    }
    // The outbound the file carried kept no dialer options that point at host interfaces or detours.
    let o = &singbox::build(p, &Mode::Tun, &[]).unwrap().config["outbounds"][0];
    assert!(o.get("detour").is_none() && o.get("bind_interface").is_none());
}

#[test]
fn hostile_xray_json_brings_in_only_the_outbound_server() {
    let a = analyze(&XRAY_HOSTILE.replace("UUID", UUID));
    assert_eq!(a.profiles.len(), 1, "{:?}", a.issues);
    let p = &a.profiles[0];
    assert_eq!(p.engine(), core_model::EngineKind::Xray);
    let x = xray::build(p, "203.0.113.7".parse().unwrap(), &up()).unwrap();
    let obj = x.config.as_object().unwrap();
    for k in obj.keys() {
        assert!(
            ["log", "inbounds", "outbounds"].contains(&k.as_str()),
            "xray: unexpected key {k}"
        );
    }
    assert_eq!(x.config["log"]["loglevel"], "warning");
    assert_eq!(x.config["inbounds"].as_array().unwrap().len(), 1);
    assert_eq!(x.config["inbounds"][0]["listen"], "127.0.0.1");
    assert_eq!(x.config["inbounds"][0]["settings"]["auth"], "password");
    let text = x.config.to_string();
    for bad in [
        "7890",
        "evil",
        "6.6.6.6",
        "StatsService",
        "HandlerService",
        "noauth",
        "routing",
    ] {
        assert!(
            !text.contains(bad),
            "xray: `{bad}` reached the config: {text}"
        );
    }
    // The sing-box side of the same profile is the generated socks outbound with the session credentials.
    let sb = singbox::build_with(
        p,
        &singbox::Options {
            mode: Some(Mode::Tun),
            upstream_socks: Some(up()),
            ..Default::default()
        },
    )
    .unwrap();
    assert_clean(&sb.config, "xray json via sing-box");
}

#[test]
fn hostile_clash_yaml_brings_in_only_the_proxy() {
    let a = analyze(CLASH_HOSTILE);
    assert_eq!(a.profiles.len(), 1, "{:?}", a.issues);
    for mode in [Mode::Tun, Mode::Proxy { socks_port: 10808 }] {
        let b = singbox::build(&a.profiles[0], &mode, &[]).unwrap();
        assert_clean(&b.config, "clash");
    }
}

#[test]
fn generated_singbox_configs_never_open_an_api() {
    // No Clash/gRPC API, no cache file, no extra listeners for any generated config.
    let a = analyze("ss://aes-256-gcm:pw-e2e-1234@s.example.com:8388#s");
    for mode in [Mode::Tun, Mode::Proxy { socks_port: 10808 }] {
        let c = singbox::build(&a.profiles[0], &mode, &[]).unwrap().config;
        assert!(c.get("experimental").is_none());
    }
}
