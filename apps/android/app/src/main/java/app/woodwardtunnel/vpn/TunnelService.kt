    // ---- helpers ----

    private fun InterfaceAddress.prefix(): String =
        if (address is Inet6Address) {
            "${Inet6Address.getByAddress(address.address).hostAddress}/$networkPrefixLength"
        } else {
            "${address.hostAddress}/$networkPrefixLength"
        }

    private fun io.nekohasekai.libbox.RoutePrefixIterator.items(): List<io.nekohasekai.libbox.RoutePrefix> {
        val l = mutableListOf<io.nekohasekai.libbox.RoutePrefix>()
        while (hasNext()) l += next()
        return l
    }

    private class Strings(values: List<String>) : StringIterator {
        private val total = values.size
        private val it = values.iterator()
        override fun len(): Int = total
        override fun hasNext(): Boolean = it.hasNext()
        override fun next(): String = it.next()
    }
}
