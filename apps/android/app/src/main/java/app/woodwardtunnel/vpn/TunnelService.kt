/**
 * Foreground VpnService that hosts sing-box (libbox). All lifecycle work (start, stop) runs on one
 * background thread so that start and stop never interleave. The configuration is generated by
 * the Rust core inside this process and handed straight to libbox; it is never put in an Intent,
 * a log line or a file we write (libbox's own snapshot file is wiped, see [EngineRuntime]).
 */
class TunnelService : VpnService(), PlatformInterface {

    companion object {
        const val ACTION_START = "app.woodwardtunnel.action.START"
        const val ACTION_STOP = "app.woodwardtunnel.action.STOP"
        const val EXTRA_PROFILE_ID = "profile_id"
        private const val TAG = "WtTunnel"
        private const val CHANNEL_ID = "tunnel"
        private const val NOTIFICATION_ID = 1

        @Volatile
        var instance: TunnelService? = null
            private set
    }

    private val worker = Executors.newSingleThreadExecutor { Thread(it, "wt-tunnel") }

    @Volatile
    private var stopRequested = false

    @Volatile
    private var running = false
    private var commandServer: CommandServer? = null
    private var tun: ParcelFileDescriptor? = null
    private var monitor: NetworkMonitor? = null

    override fun onCreate() {
        super.onCreate()
        instance = this
    }

    override fun onStartCommand(intent: Intent?, flags: Int, startId: Int): Int {
        when (intent?.action) {
            ACTION_START -> {
                showForeground(getString(R.string.notif_connecting))
                val id = intent.getStringExtra(EXTRA_PROFILE_ID)
                if (id == null || running) {
                    if (!running) stopForegroundAndSelf()
                } else {
                    running = true
                    stopRequested = false
                    worker.execute { start(id) }
                }
            }
            ACTION_STOP -> requestStop()
            else -> if (!running) stopForegroundAndSelf()
        }
        return START_NOT_STICKY
    }

    override fun onBind(intent: Intent?): IBinder? = super.onBind(intent)

    override fun onRevoke() {
        // The user (or another VPN app) took the VPN away.
        TunnelState.set(ConnState.Error(R.string.err_revoked))
        requestStop(keepError = true)
    }

    override fun onDestroy() {
        instance = null
        worker.shutdown()
        super.onDestroy()
    }

    fun requestStop(keepError: Boolean = false) {
        stopRequested = true
        try {
            worker.execute { teardown(keepError) }
        } catch (_: java.util.concurrent.RejectedExecutionException) {
        }
    }

    // ---- lifecycle (worker thread) ----

    private fun start(profileId: String) {
        TunnelState.set(ConnState.Connecting)
        val plan = try {
            Core.get().launchPlan(profileId, Prefs.dnsServers(this))
        } catch (e: Exception) {
            fail(R.string.err_core, coreMessage = e.coreMessage())
            return
        }
        val config: String
        val insecure: Boolean
        when (plan) {
            is FfiLaunchPlan.SingBox -> {
                config = plan.configJson
                insecure = plan.insecureTls
            }
            is FfiLaunchPlan.AmneziaWg, is FfiLaunchPlan.OpenVpn -> {
                fail(R.string.err_unsupported_protocol)
                return
            }
        }
        if (stopRequested) return
        try {
            EngineRuntime.ensureSetup(this)
            monitor = NetworkMonitor(this).also { it.start() }
            val server = CommandServer(handler, this)
            commandServer = server
            server.start()
            server.startOrReloadService(config, OverrideOptions())
        } catch (e: Throwable) {
            fail(R.string.err_engine, technical = e.message)
            return
        } finally {
            EngineRuntime.wipeSnapshots(this)
        }
        if (stopRequested) return

        // Connected only once traffic provably flows through the tunnel.
        var ok = false
        for (attempt in 0 until 3) {
            if (stopRequested) return
            if (Probe.reachable()) {
                ok = true
                break
            }
        }
        if (stopRequested) return
        if (!ok) {
            fail(R.string.err_no_internet)
            return
        }
        TunnelState.set(ConnState.Connected(SystemClock.elapsedRealtime(), insecure))
        showForeground(getString(R.string.notif_text))
    }

    /** Failure path (worker thread): record a plain message, tear everything down, keep the error visible. */
    private fun fail(message: Int, coreMessage: String? = null, technical: String? = null) {
        TunnelState.set(ConnState.Error(message, coreMessage), technical)
        teardown(keepError = true)
    }

    private fun teardown(keepError: Boolean) {
        if (!running) return // already torn down (a failure path ran first)
        runCatching { commandServer?.closeService() }
        runCatching { commandServer?.close() }
        commandServer = null
        runCatching { tun?.close() }
        tun = null
        monitor?.stop()
        monitor = null
        EngineRuntime.wipeSnapshots(this)
        running = false
        if (!keepError) TunnelState.set(ConnState.Disconnected)
        stopForegroundAndSelf()
    }

    private fun stopForegroundAndSelf() {
        ServiceCompat.stopForeground(this, ServiceCompat.STOP_FOREGROUND_REMOVE)
        stopSelf()
    }

    // ---- notification ----

    private fun showForeground(text: String) {
        val nm = getSystemService(NotificationManager::class.java)
        if (Build.VERSION.SDK_INT >= 26 && nm.getNotificationChannel(CHANNEL_ID) == null) {
            nm.createNotificationChannel(
                NotificationChannel(CHANNEL_ID, getString(R.string.notif_channel), NotificationManager.IMPORTANCE_LOW),
            )
        }
        val open = PendingIntent.getActivity(
            this, 0, Intent(this, MainActivity::class.java).addFlags(Intent.FLAG_ACTIVITY_SINGLE_TOP),
            PendingIntent.FLAG_IMMUTABLE or PendingIntent.FLAG_UPDATE_CURRENT,
        )
        val stop = PendingIntent.getService(
            this, 1, Intent(this, TunnelService::class.java).setAction(ACTION_STOP),
            PendingIntent.FLAG_IMMUTABLE or PendingIntent.FLAG_UPDATE_CURRENT,
        )
        val n: Notification = NotificationCompat.Builder(this, CHANNEL_ID)
            .setSmallIcon(R.drawable.ic_stat_tunnel)
            .setContentTitle(getString(R.string.app_name))
            .setContentText(text)
            .setOngoing(true)
            .setOnlyAlertOnce(true)
            .setShowWhen(false)
            .setContentIntent(open)
            .addAction(0, getString(R.string.notif_stop), stop)
            .build()
        val type = if (Build.VERSION.SDK_INT >= 29) ServiceInfo.FOREGROUND_SERVICE_TYPE_SYSTEM_EXEMPTED else 0
        ServiceCompat.startForeground(this, NOTIFICATION_ID, n, type)
    }

    // ---- libbox callbacks ----

    private val handler = object : CommandServerHandler {
        override fun serviceStop() = requestStop()
        override fun serviceReload() = requestStop()
        override fun getSystemProxyStatus(): SystemProxyStatus = SystemProxyStatus()
        override fun setSystemProxyEnabled(enabled: Boolean) {}
        override fun triggerNativeCrash() {}
        override fun writeDebugMessage(message: String?) {} // engine text is never logged
        override fun connectSSHAgent(): Int = -1
    }

    override fun usePlatformAutoDetectInterfaceControl(): Boolean = true

    override fun autoDetectInterfaceControl(fd: Int) {
        if (!protect(fd)) Log.w(TAG, "protect failed")
    }

    override fun openTun(options: TunOptions): Int {
        if (prepare(this) != null) error("vpn permission missing")
        val b = Builder().setSession(getString(R.string.app_name)).setMtu(options.mtu)
        if (Build.VERSION.SDK_INT >= 29) b.setMetered(false)
        PendingIntent.getActivity(
            this, 2, Intent(this, MainActivity::class.java),
            PendingIntent.FLAG_IMMUTABLE or PendingIntent.FLAG_UPDATE_CURRENT,
        ).let { b.setConfigureIntent(it) }

        for (it in options.inet4Address.items()) b.addAddress(it.address(), it.prefix())
        for (it in options.inet6Address.items()) b.addAddress(it.address(), it.prefix())

        if (options.autoRoute) {
            if (options.dnsMode.value != Libbox.DNSModeDisabled) {
                val dns = options.dnsServerAddress
                while (dns.hasNext()) b.addDnsServer(dns.next())
            }
            if (Build.VERSION.SDK_INT >= 33) {
                val v4 = options.inet4RouteAddress.items()
                if (v4.isNotEmpty()) v4.forEach { b.addRoute(IpPrefix(InetAddress.getByName(it.address()), it.prefix())) }
                else if (options.inet4Address.hasNext()) b.addRoute("0.0.0.0", 0)
                val v6 = options.inet6RouteAddress.items()
                if (v6.isNotEmpty()) v6.forEach { b.addRoute(IpPrefix(InetAddress.getByName(it.address()), it.prefix())) }
                else if (options.inet6Address.hasNext()) b.addRoute("::", 0)
                options.inet4RouteExcludeAddress.items().forEach { b.excludeRoute(IpPrefix(InetAddress.getByName(it.address()), it.prefix())) }
                options.inet6RouteExcludeAddress.items().forEach { b.excludeRoute(IpPrefix(InetAddress.getByName(it.address()), it.prefix())) }
            } else {
                options.inet4RouteRange.items().forEach { b.addRoute(it.address(), it.prefix()) }
                options.inet6RouteRange.items().forEach { b.addRoute(it.address(), it.prefix()) }
            }
            val include = options.includePackage
            while (include.hasNext()) runCatching { b.addAllowedApplication(include.next()) }
            val exclude = options.excludePackage
            while (exclude.hasNext()) runCatching { b.addDisallowedApplication(exclude.next()) }
        }
        if (options.isHTTPProxyEnabled && Build.VERSION.SDK_INT >= 29) {
            // The core never asks for a system HTTP proxy; honour it only if present.
            b.setHttpProxy(ProxyInfo.buildDirectProxy(options.httpProxyServer, options.httpProxyServerPort))
        }
        val pfd = b.establish() ?: error("vpn establish refused")
        tun = pfd
        return pfd.fd
    }

    override fun useProcFS(): Boolean = Build.VERSION.SDK_INT < 29

    override fun findConnectionOwner(
        ipProtocol: Int, sourceAddress: String?, sourcePort: Int, destinationAddress: String?, destinationPort: Int,
    ): ConnectionOwner = error("not supported")

    override fun startDefaultInterfaceMonitor(listener: InterfaceUpdateListener?) {
        monitor?.setListener(listener)
    }

    override fun closeDefaultInterfaceMonitor(listener: InterfaceUpdateListener?) {
        monitor?.setListener(null)
    }

    override fun getInterfaces(): NetworkInterfaceIterator {
        val cm = getSystemService(android.net.ConnectivityManager::class.java)
        val javaIfs = NetworkInterface.getNetworkInterfaces()?.toList().orEmpty()
        val out = mutableListOf<LibboxNetworkInterface>()
        for (network in cm.allNetworks) {
            val lp = cm.getLinkProperties(network) ?: continue
            val caps = cm.getNetworkCapabilities(network) ?: continue
            val ji = javaIfs.find { it.name == lp.interfaceName } ?: continue
            val li = LibboxNetworkInterface()
            li.name = lp.interfaceName
            li.index = ji.index
            runCatching { li.mtu = ji.mtu }
            li.dnsServer = Strings(lp.dnsServers.mapNotNull { it.hostAddress })
            li.gateway = Strings(
                lp.routes.filter { it.destination.prefixLength == 0 }
                    .mapNotNull { it.gateway }.filterNot { it.isAnyLocalAddress }.mapNotNull { it.hostAddress },
            )
            li.type = when {
                caps.hasTransport(android.net.NetworkCapabilities.TRANSPORT_WIFI) -> Libbox.InterfaceTypeWIFI
                caps.hasTransport(android.net.NetworkCapabilities.TRANSPORT_CELLULAR) -> Libbox.InterfaceTypeCellular
                caps.hasTransport(android.net.NetworkCapabilities.TRANSPORT_ETHERNET) -> Libbox.InterfaceTypeEthernet
                else -> Libbox.InterfaceTypeOther
            }
            li.addresses = Strings(ji.interfaceAddresses.map { it.prefix() })
            var flags = 0
            if (caps.hasCapability(android.net.NetworkCapabilities.NET_CAPABILITY_INTERNET)) {
                flags = OsConstants.IFF_UP or OsConstants.IFF_RUNNING
            }
            if (ji.isLoopback) flags = flags or OsConstants.IFF_LOOPBACK
            if (ji.isPointToPoint) flags = flags or OsConstants.IFF_POINTOPOINT
            if (ji.supportsMulticast()) flags = flags or OsConstants.IFF_MULTICAST
            li.flags = flags
            li.metered = !caps.hasCapability(android.net.NetworkCapabilities.NET_CAPABILITY_NOT_METERED)
            out += li
        }
        return object : NetworkInterfaceIterator {
            private val it = out.iterator()
            override fun hasNext() = it.hasNext()
            override fun next(): LibboxNetworkInterface = it.next()
        }
    }

